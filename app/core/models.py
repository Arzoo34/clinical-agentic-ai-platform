"""Core data models and dataclasses for the agentic clinical trial platform."""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional


class Severity(str, Enum):
    """Severity levels for anomalies and alerts."""
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class RiskLevel(str, Enum):
    """Risk levels for datasets and sites."""
    LOW = "low"
    MODERATE = "moderate"
    HIGH = "high"
    CRITICAL = "critical"


@dataclass
class FileMetadata:
    """Metadata extracted during file ingestion."""
    filename: str
    file_path: str
    study_id: Optional[str] = None
    site_id: Optional[str] = None
    file_type: str = "xlsx"
    row_count: int = 0
    column_count: int = 0
    modification_time: Optional[str] = None
    file_size: int = 0
    checksum: Optional[str] = None
    sheet_names: List[str] = field(default_factory=list)


@dataclass
class DataQualityMetrics:
    """Quality scores and metrics for a dataset."""
    dataset_name: str
    completeness_score: float = 100.0
    validity_score: float = 100.0
    consistency_score: float = 100.0
    overall_quality_score: float = 100.0
    row_count: int = 0
    duplicate_count: int = 0
    outlier_count: int = 0
    issues: List[str] = field(default_factory=list)
    column_stats: Dict[str, Any] = field(default_factory=dict)


@dataclass
class Anomaly:
    """Detected anomaly."""
    anomaly_id: str
    anomaly_type: str
    severity: Severity
    metric_name: str
    observed_value: float
    expected_value: Optional[float] = None
    confidence: float = 0.9
    study_id: Optional[str] = None
    site_id: Optional[str] = None
    reason: str = ""
    dataset_name: Optional[str] = None
    timestamp: Optional[str] = None

    def __post_init__(self):
        if self.timestamp is None:
            self.timestamp = datetime.now(timezone.utc).isoformat()


@dataclass
class RiskScore:
    """Risk score calculated for a dataset, study, or overall."""
    dataset_name: str
    overall_score: float
    risk_level: RiskLevel
    quality_component: float = 0.0
    operational_component: float = 0.0
    anomaly_component: float = 0.0
    study_id: Optional[str] = None
    site_id: Optional[str] = None
    affected_records: int = 0
    evidence: List[str] = field(default_factory=list)
    recommended_action: str = ""


@dataclass
class Alert:
    """Alert generated by alert agent."""
    alert_id: str
    severity: Severity
    title: str
    description: str
    study_id: Optional[str] = None
    site_id: Optional[str] = None
    evidence: List[str] = field(default_factory=list)
    recommended_action: str = ""
    status: str = "open"
    created_at: Optional[str] = None
    related_anomalies: List[str] = field(default_factory=list)

    def __post_init__(self):
        if self.created_at is None:
            self.created_at = datetime.now(timezone.utc).isoformat()


@dataclass
class OperationalKPI:
    """Operational KPI tracked across studies or sites."""
    kpi_id: str
    name: str
    metric_name: str
    value: float
    target_value: Optional[float] = None
    status: str = "normal"  # normal, warning, critical
    study_id: Optional[str] = None
    site_id: Optional[str] = None
    description: str = ""
    details: Dict[str, Any] = field(default_factory=dict)


@dataclass
class AgentResult:
    """Execution result returned by an agent."""
    agent_name: str
    success: bool = True
    data: Dict[str, Any] = field(default_factory=dict)
    warnings: List[str] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)
    execution_time_seconds: float = 0.0


@dataclass
class PipelineContext:
    """Shared context passed across all agents in the pipeline."""
    session_id: str
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    completed_at: Optional[str] = None
    ingestion_metadata: List[FileMetadata] = field(default_factory=list)
    harmonized_data: Dict[str, Any] = field(default_factory=dict)
    quality_metrics: Dict[str, DataQualityMetrics] = field(default_factory=dict)
    operational_kpis: List[OperationalKPI] = field(default_factory=list)
    anomalies: List[Anomaly] = field(default_factory=list)
    risk_scores: List[RiskScore] = field(default_factory=list)
    alerts: List[Alert] = field(default_factory=list)
    insights: List[str] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
